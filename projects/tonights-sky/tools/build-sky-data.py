"""Rebuild sky-data.js from its two public sources. Development helper only; the
workshop never runs it and never downloads anything.

Inputs (download them yourself, then pass the paths):
  1. Yale Bright Star Catalogue, 5th revised ed. (Hoffleit & Warren 1991), as the
     HEASARC "bsc5p" table in TDAT format:
     https://heasarc.gsfc.nasa.gov/FTP/heasarc/dbase/tdat_files/heasarc_bsc5p.tdat.gz
  2. d3-celestial constellation data by Olaf Frohn (BSD 3-Clause):
     https://github.com/ofrohn/d3-celestial/blob/master/data/constellations.lines.json
     https://github.com/ofrohn/d3-celestial/blob/master/data/constellations.json

    python tools/build-sky-data.py heasarc_bsc5p.tdat constellations.lines.json constellations.json

Keeps stars of visual magnitude 4.5 and brighter (about 900), J2000 positions
rounded to 0.01 degree, and a short Bayer/Flamsteed label. Writes sky-data.js.
"""
import json, re, sys, pathlib

MAG_LIMIT = 4.5
# T Coronae Borealis (HR 5958) is listed at its 1946 outburst brightness (mag 2); it normally
# sits near magnitude 10, so it is left out rather than drawn as a bright star.
EXCLUDE = {5958}
GREEK = {"Alp": "α", "Bet": "β", "Gam": "γ", "Del": "δ", "Eps": "ε", "Zet": "ζ", "Eta": "η",
         "The": "θ", "Iot": "ι", "Kap": "κ", "Lam": "λ", "Mu": "μ", "Nu": "ν", "Xi": "ξ",
         "Omi": "ο", "Pi": "π", "Rho": "ρ", "Sig": "σ", "Tau": "τ", "Ups": "υ", "Phi": "φ",
         "Chi": "χ", "Psi": "ψ", "Ome": "ω"}
SUP = str.maketrans("0123456789", "⁰¹²³⁴⁵⁶⁷⁸⁹")


def label(alt):
    """'9Alp CMa' -> ('α', 'CMa'); 'Alp1Cen' -> ('α¹', 'Cen'); '47 UMa' -> ('47', 'UMa')."""
    alt = alt.strip()
    m = re.match(r"^(\d*)\s*([A-Z][a-z]{1,2})\s*(\d?)\s*([A-Z][A-Za-z]{2})$", alt)
    if m and m.group(2) in GREEK:
        return GREEK[m.group(2)] + m.group(3).translate(SUP), m.group(4)
    m = re.match(r"^(\d+)\s*([A-Z][A-Za-z]{2})$", alt)
    if m:
        return m.group(1), m.group(2)
    return "", ""


def main(tdat, lines_path, names_path):
    text = pathlib.Path(tdat).read_text(encoding="latin-1")
    fields = [l.split("=")[0].strip()[6:-1] for l in text.splitlines() if l.startswith("field[")]
    body = text.split("<DATA>")[1].split("<END>")[0].strip().splitlines()
    stars = []
    for row in body:
        d = dict(zip(fields, row.split("|")))
        if not d.get("vmag") or float(d["vmag"]) > MAG_LIMIT or not d.get("ra") or int(d["hr"]) in EXCLUDE:
            continue
        bayer, con = label(d.get("alt_name", ""))
        bv = round(float(d["bv_color"]), 2) if d.get("bv_color") else 0.6
        stars.append([round(float(d["ra"]), 2), round(float(d["dec"]), 2),
                      round(float(d["vmag"]), 2), bv, int(d["hr"]), bayer, con])
    stars.sort(key=lambda s: s[2])
    lines = json.loads(pathlib.Path(lines_path).read_text(encoding="utf-8"))
    names = json.loads(pathlib.Path(names_path).read_text(encoding="utf-8"))
    cons = {}
    for f in names["features"]:
        p = f["properties"]
        cons[f["id"]] = {"name": p["name"], "en": p["en"], "gen": p["gen"], "rank": int(p["rank"])}
    figures = []
    for f in lines["features"]:
        polys = [[[round(ra % 360, 2), round(dec, 2)] for ra, dec in poly]
                 for poly in f["geometry"]["coordinates"]]
        figures.append([f["id"], polys])
    out = ("/* Generated by tools/build-sky-data.py. Do not edit by hand.\n"
           " * stars: [RA deg, Dec deg (J2000), V magnitude, B-V colour, HR number, Bayer/Flamsteed, constellation]\n"
           " *   from the Yale Bright Star Catalogue, 5th revised ed. (Hoffleit & Warren 1991), via NASA HEASARC.\n"
           " * figures/constellations: constellation stick figures and names from d3-celestial,\n"
           " *   Copyright (c) 2015 Olaf Frohn, BSD 3-Clause License (see THIRD-PARTY.md). */\n"
           "(function (root) {\n  var SKY_DATA = {\n    magLimit: " + str(MAG_LIMIT) + ",\n"
           "    stars: " + json.dumps(stars, ensure_ascii=False, separators=(",", ":")) + ",\n"
           "    constellations: " + json.dumps(cons, ensure_ascii=False, separators=(",", ":")) + ",\n"
           "    figures: " + json.dumps(figures, separators=(",", ":")) + "\n  };\n"
           "  if (typeof module === 'object' && module.exports) module.exports = SKY_DATA;\n"
           "  else root.SKY_DATA = SKY_DATA;\n})(this);\n")
    dest = pathlib.Path(__file__).resolve().parents[1] / "sky-data.js"
    dest.write_text(out, encoding="utf-8", newline="\n")
    print(f"Wrote {dest.name}: {len(stars)} stars, {len(figures)} figures, {len(cons)} constellation names")


if __name__ == "__main__":
    main(*sys.argv[1:4])
